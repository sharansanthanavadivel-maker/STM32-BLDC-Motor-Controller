/*
 * STM32F401RE BLDC pre-flight diagnostic application.
 * CubeMX must generate and initialize: hi2c1, hadc1, htim1, GPIO.
 * ESC output is disabled by default and only enabled during the controlled test.
 */
#include "main.h"
#include "ina219.h"
#include "ssd1306.h"
#include <stdio.h>

extern I2C_HandleTypeDef hi2c1;
extern ADC_HandleTypeDef hadc1;
extern TIM_HandleTypeDef htim1;

static INA219_t ina219;
static SystemState_t state = SYS_IDLE;

static void leds(bool r, bool g, bool b) {
    HAL_GPIO_WritePin(LED_R_GPIO_Port, LED_R_Pin, r ? GPIO_PIN_SET : GPIO_PIN_RESET);
    HAL_GPIO_WritePin(LED_G_GPIO_Port, LED_G_Pin, g ? GPIO_PIN_SET : GPIO_PIN_RESET);
    HAL_GPIO_WritePin(LED_B_GPIO_Port, LED_B_Pin, b ? GPIO_PIN_SET : GPIO_PIN_RESET);
}
static void buzzer(bool on) {
    HAL_GPIO_WritePin(BUZZER_GPIO_Port, BUZZER_Pin, on ? GPIO_PIN_SET : GPIO_PIN_RESET);
}
static void esc_pulse_us(uint16_t pulse_us) {
    /* Requires TIM1 configured for 1 MHz counter and 20 ms period (50 Hz). */
    __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_1, pulse_us);
}
static void esc_disable(void) {
    esc_pulse_us(ESC_MIN_US);
    HAL_TIM_PWM_Stop(&htim1, TIM_CHANNEL_1);
}
static bool read_battery_voltage(float *volts) {
    if (HAL_ADC_Start(&hadc1) != HAL_OK) return false;
    if (HAL_ADC_PollForConversion(&hadc1, 20) != HAL_OK) {
        HAL_ADC_Stop(&hadc1); return false;
    }
    uint32_t raw = HAL_ADC_GetValue(&hadc1);
    HAL_ADC_Stop(&hadc1);
    /* Assumes 12-bit ADC, 3.3 V reference, external divider ratio configured above. */
    *volts = ((float)raw / 4095.0f) * 3.3f * VBAT_DIVIDER_RATIO;
    return true;
}
static void indicate(SystemState_t s) {
    state = s;
    switch (s) {
    case SYS_IDLE: leds(false,false,true); buzzer(false); break;
    case SYS_TESTING: leds(true,false,false); buzzer(false); break;
    case SYS_PASS: leds(false,true,false); buzzer(false); break;
    default: leds(true,true,false); buzzer(true); break;
    }
}
static void run_preflight_test(void) {
    float vbat = 0.0f, current = 0.0f;
    indicate(SYS_TESTING);
    if (!read_battery_voltage(&vbat) || vbat < VBAT_MIN_V) {
        esc_disable(); indicate(SYS_LOW_BATTERY); return;
    }
    if (HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_1) != HAL_OK) {
        indicate(SYS_SENSOR_ERROR); return;
    }
    esc_pulse_us(ESC_TEST_US);
    HAL_Delay(TEST_DURATION_MS);
    esc_pulse_us(ESC_MIN_US);
    HAL_Delay(300);
    esc_disable();

    if (!INA219_ReadCurrentA(&ina219, &current)) {
        indicate(SYS_SENSOR_ERROR); return;
    }
    if (current < CURRENT_MIN_A) { indicate(SYS_LOW_CURRENT); return; }
    if (current > CURRENT_MAX_A) { indicate(SYS_OVERCURRENT); return; }
    indicate(SYS_PASS);
}
int main(void) {
    HAL_Init();
    SystemClock_Config(); /* Generated by CubeMX in the project. */
    MX_GPIO_Init();
    MX_I2C1_Init();
    MX_ADC1_Init();
    MX_TIM1_Init();

    esc_disable();
    if (!INA219_Init(&ina219, &hi2c1, INA219_I2C_ADDR, 0.001f, 0.1f)) {
        indicate(SYS_SENSOR_ERROR);
    } else {
        (void)SSD1306_Init(&hi2c1, OLED_I2C_ADDR);
        indicate(SYS_IDLE);
    }

    while (1) {
        /* Trigger the test from a user-operated button in the final integration.
           This scaffold runs one test every 5 seconds for bench development only. */
        run_preflight_test();
        HAL_Delay(5000);
        indicate(SYS_IDLE);
    }
}

